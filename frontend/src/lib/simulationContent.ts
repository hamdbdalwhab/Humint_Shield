/** Resolve the content for any tracking channel, falling back to email copy. */
export function contentForChannel(channel: string | null | undefined): ChannelContent {
  if (
    channel === 'qr' ||
    channel === 'vishing' ||
    channel === 'pretexting' ||
    channel === 'usb'
  ) {
    return CHANNEL_CONTENT[channel];
  }
  return EMAIL_CONTENT;
}
